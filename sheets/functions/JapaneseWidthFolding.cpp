struct CharPair {
    char16_t key;
    char16_t value;
};

struct SoundMarkEntry {
    char16_t key;
    char16_t first;
    char16_t second;
};

template<typename Entry, std::size_t N>
const Entry *find(const std::array<Entry, N> &table, char16_t key)
{
    const auto it = std::lower_bound(table.begin(), table.end(), key, [](const Entry &e, char16_t k) {
        return e.key < k;
    });
    return (it != table.end() && it->key == key) ? &*it : nullptr;
}

