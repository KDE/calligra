// GA -> KA + voiced-sound-mark, etc.
QString decomposeJaVoicedSoundMarks(const QString &input)
{
    QString result;
    result.reserve(input.length() * 2);
    for (const QChar &c : input) {
        if (const auto *e = find(katakanaDecomposition, c.unicode())) {
            result += QChar(e->first);
            result += QChar(e->second);
        } else {
            result += c;
        }
    }
    return result;
}

// KA + voiced-sound-mark -> GA, etc. useCombinedVu=false keeps U+voiced-mark separate (JIS()).
QString composeJaVoicedSoundMarks(const QString &input, bool useCombinedVu)
{
    QString result;
    result.reserve(input.length());

    int i = 0;
    while (i < input.length()) {
        const QChar c = input.at(i);
        if (i + 1 < input.length()) {
            // 0x3099/0x309B voiced, 0x309A/0x309C semi-voiced (combining or spacing form)
            int j = input.at(i + 1).unicode() - 0x3099;
            if (j == 2 || j == 3)
                j -= 2;
            if (j == 0 || j == 1) {
                if (const auto *e = find(voicedComposition, c.unicode())) {
                    const char16_t candidate = (j == 0) ? e->first : e->second;
                    if (candidate != 0 && !(c.unicode() == 0x30A6 && !useCombinedVu)) {
                        result += QChar(candidate);
                        i += 2;
                        continue;
                    }
                }
            }
        }
        result += c;
        ++i;
    }
    return result;
}

