QString toHalfWidthForAsc(const QString &input)
{
    const QString decomposed = decomposeJaVoicedSoundMarks(input);

    QString result;
    result.reserve(decomposed.length());
    for (const QChar &c : decomposed) {
        const auto *e = find(fullToHalfForAsc, c.unicode());
        result += e ? QChar(e->value) : c;
    }
    return result;
}

QString toFullWidthForJis(const QString &input)
{
    QString mapped;
    mapped.reserve(input.length());
    for (const QChar &c : input) {
        const auto *e = find(halfToFullForJis, c.unicode());
        mapped += e ? QChar(e->value) : c;
    }

    return composeJaVoicedSoundMarks(mapped, false);
}

